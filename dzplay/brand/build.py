#!/usr/bin/env python3
"""DALTA.BIT brand assets: one generator, two masters.

The masters are brand/logo-large.svg (48 px and up) and brand/logo-small.svg (16–24 px and the notification icon).
Every icon the app ships is made from them here; never edit a generated file by hand (BRAND.md):

    cd dzplay && .venv/bin/python brand/build.py          # everything (renders with Chromium through Playwright)
    cd dzplay && .venv/bin/python brand/build.py --check  # the text outputs only, no browser: exit 1 if stale

The dot glows (a radial gradient + a soft halo) everywhere except the two flat system icons, the Android
notification icon and the Android 13 themed (monochrome) icon: one colour, no halo. Nothing is ever mirrored.
"""

from __future__ import annotations

import argparse
import base64
import io
import json
import math
import os
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]  # dzplay/
BRAND = ROOT / "brand"
STATIC = ROOT / "static"
ICONS = STATIC / "icons"
RES = ROOT / "android" / "app" / "src" / "main" / "res"
EXPORT = BRAND / "export"
NS = "{http://www.w3.org/2000/svg}"

BLACK, WHITE, RED = "#0B0B0D", "#FFFFFF", "#E5232D"
APP_NAME = "DALTA.BIT"  # the default of settings.APP_NAME; --name for another one (og:image and the lockups only)
TAGLINE = "مجتمع للمتداولين ولمشاركة أخبار العملات الرقمية والتحليلات والأفكار"

# Android adaptive icon: a 108-unit canvas, the launcher shows its 72-unit centre through a mask and guarantees a
# 66-unit circle. The 100-unit mark is scaled so every pixel it draws (alpha ≥ 10 %) stays inside that circle
# (checked by tests/test_brand_assets.py). The panel preview uses the same value.
FG_SCALE = 0.57
DENSITIES = {"mdpi": 1, "hdpi": 1.5, "xhdpi": 2, "xxhdpi": 3, "xxxhdpi": 4}
GENERATED = "Generated by brand/build.py from brand/logo-large.svg and brand/logo-small.svg. Do not edit: run it."


# ------------------------------------------------------------------ the masters

def master(size: str) -> str:
    return (BRAND / f"logo-{size}.svg").read_text(encoding="utf-8")


def mark(size: str, ink: str, *, flat: bool = False, uid: str = "") -> str:
    """The mark's shapes (no <svg>): `ink` for the candles, the glowing dot unless `flat` (one colour, no halo).
    `uid` keeps the gradient ids unique when several copies share one document."""
    text = master(size)
    s = re.sub(r"<!--.*?-->", "", text[text.index(">", text.index("<svg")) + 1: text.rindex("</svg>")], flags=re.S)
    s = s.replace("currentColor", ink)
    if flat:
        s = re.sub(r"<defs>.*?</defs>", "", s, flags=re.S)
        s = re.sub(r'\s*<circle class="glow"[^>]*/>', "", s)
        s = re.sub(r'(<circle class="dot"[^>]*fill=")[^"]*(")', rf"\g<1>{ink}\2", s)
    for gid in sorted(set(re.findall(r'id="([^"]+)"', s))) if uid else ():
        s = s.replace(f'id="{gid}"', f'id="{gid}{uid}"').replace(f"url(#{gid})", f"url(#{gid}{uid})")
    return "\n".join(line for line in s.strip().splitlines() if line.strip())


def num(v: float) -> str:
    return f"{float(v):g}"


def placed(size: str, ink: str, scale: float, view: float = 100, **kw) -> str:
    """The mark centred on a view×view canvas, scaled."""
    off = view / 2 - 50 * scale
    return f'<g transform="translate({num(off)} {num(off)}) scale({num(scale)})">{mark(size, ink, **kw)}</g>'


def shapes(size: str) -> dict:
    """The master as data: candles and base [x, y, w, h, rx], the dot, its halo and their gradients."""
    root = ET.fromstring(master(size))
    grads = {g.get("id"): g for g in root.iter(NS + "radialGradient")}
    circles = {c.get("class"): c for c in root.iter(NS + "circle")}
    dot, glow = circles["dot"], circles["glow"]
    dot_grad, glow_grad = grads[dot.get("fill")[5:-1]], grads[glow.get("fill")[5:-1]]
    stops = lambda g: [[float(s.get("offset")), s.get("stop-color")] + ([float(s.get("stop-opacity"))] if s.get("stop-opacity") else [])
                       for s in g.iter(NS + "stop")]
    return {
        "ink": [[float(r.get(k)) for k in ("x", "y", "width", "height", "rx")] for r in root.iter(NS + "rect")],
        "dot": [float(dot.get(k)) for k in ("cx", "cy", "r")],
        "dotGradient": {"cx": float(dot_grad.get("cx")), "cy": float(dot_grad.get("cy")), "r": float(dot_grad.get("r")),
                        "stops": stops(dot_grad)},
        "glow": float(glow.get("r")),
        "glowStops": stops(glow_grad),
    }


# ------------------------------------------------------------------ text outputs (checked by --check)

def logo_shapes_js() -> str:
    data = {size: shapes(size) for size in ("large", "small")}
    body = ",\n".join(f"  {size}: {json.dumps(v, separators=(',', ':'))}" for size, v in data.items())
    return (f"// {GENERATED}\n// The logo's shapes for the interface (ui.js logoMark): large from 48 px, small for 16–24 px.\n"
            f"export const LOGO = {{\n{body},\n}};\n")


def favicon_svg() -> str:
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100">\n<!-- {GENERATED} -->\n'
            f'<rect width="100" height="100" rx="22" fill="{BLACK}"/>\n{placed("small", WHITE, 0.8)}\n</svg>\n')


ADAPTIVE = f"""<?xml version="1.0" encoding="utf-8"?>
<!-- {GENERATED} -->
<!-- Adaptive icon: the brand black + the logo (glowing dot); Android 13 themed icons use the flat monochrome. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/iconBackground" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground" />
    <monochrome android:drawable="@mipmap/ic_launcher_monochrome" />
</adaptive-icon>
"""


def _rounded_rect(x: float, y: float, w: float, h: float, r: float) -> str:
    """Clockwise, like the dot, so overlapping shapes add up (non-zero fill)."""
    r = min(r, w / 2, h / 2)
    return (f"M{num(x + r)},{num(y)}H{num(x + w - r)}A{num(r)},{num(r)} 0,0 1,{num(x + w)},{num(y + r)}"
            f"V{num(y + h - r)}A{num(r)},{num(r)} 0,0 1,{num(x + w - r)},{num(y + h)}H{num(x + r)}"
            f"A{num(r)},{num(r)} 0,0 1,{num(x)},{num(y + h - r)}V{num(y + r)}A{num(r)},{num(r)} 0,0 1,{num(x + r)},{num(y)}Z")


def notification_xml() -> str:
    """The status-bar icon: the small version, white and flat (Android draws only its alpha)."""
    s = shapes("small")
    cx, cy, r = s["dot"]
    paths = [_rounded_rect(*rect) for rect in s["ink"]]
    paths.append(f"M{num(cx - r)},{num(cy)}A{num(r)},{num(r)} 0,1 1,{num(cx + r)},{num(cy)}A{num(r)},{num(r)} 0,1 1,{num(cx - r)},{num(cy)}Z")
    return (f'<?xml version="1.0" encoding="utf-8"?>\n<!-- {GENERATED} -->\n'
            "<!-- Notification icon: the small logo, white and flat (no glow), as the status bar requires. -->\n"
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:width="24dp" android:height="24dp" android:viewportWidth="100" android:viewportHeight="100">\n'
            f'    <path android:fillColor="#FFFFFFFF"\n        android:pathData="{"".join(paths)}" />\n</vector>\n')


def text_outputs() -> dict[Path, str]:
    return {
        STATIC / "js" / "logo-shapes.js": logo_shapes_js(),
        ICONS / "icon.svg": favicon_svg(),
        ICONS / "logo-large.svg": master("large"),
        ICONS / "logo-small.svg": master("small"),
        RES / "mipmap-anydpi-v26" / "ic_launcher.xml": ADAPTIVE,
        RES / "mipmap-anydpi-v26" / "ic_launcher_round.xml": ADAPTIVE,
        RES / "drawable" / "ic_notification.xml": notification_xml(),
    }


# ------------------------------------------------------------------ images (rendered by Chromium)

def svg(view: float, content: str, w: int, h: int | None = None, box: str | None = None) -> str:
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{box or f"0 0 {num(view)} {num(view)}"}" '
            f'width="{w}" height="{h or w}">{content}</svg>')


BACKS = {
    "rounded": f'<rect width="100" height="100" rx="22" fill="{BLACK}"/>',  # PWA, favicon
    "inset": f'<rect x="4" y="4" width="92" height="92" rx="20" fill="{BLACK}"/>',  # Android before 8 (legacy)
    "circle": f'<circle cx="50" cy="50" r="46" fill="{BLACK}"/>',  # Android before 8, round launchers
    "full": f'<rect width="100" height="100" fill="{BLACK}"/>',  # maskable, iOS, Telegram: the system rounds it
}


def tile(size: str, scale: float, back: str = "rounded") -> str:
    """The app icon outside Android's adaptive system: the brand black + the mark."""
    return BACKS[back] + placed(size, WHITE, scale)


def _font_face() -> str:
    faces = []
    for part, rng in (("latin", "U+0000-00FF, U+2000-206F"), ("arabic", "U+0600-06FF, U+FB50-FDFF, U+FE70-FEFF")):
        data = base64.b64encode((STATIC / "fonts" / f"plex-arabic-{part}-700.woff2").read_bytes()).decode()
        faces.append(f'@font-face {{ font-family: "Plex"; font-weight: 700; src: url(data:font/woff2;base64,{data}) format("woff2"); unicode-range: {rng}; }}')
    return "\n".join(faces)


def wordmark_html(name: str, size: int, ink: str) -> str:
    first, dot, rest = name.partition(".")
    dot_el = (f'<span style="display:inline-block;width:.3em;height:.3em;border-radius:50%;background:{RED};'
              f'box-shadow:0 0 .35em rgba(229,35,45,.6);margin:0 .04em"></span>') if dot else ""
    return (f'<div style="font:700 {size}px Plex, sans-serif;color:{ink};direction:ltr;display:flex;align-items:baseline;'
            f'letter-spacing:-.02em;line-height:1">{first}{dot_el}{rest}</div>')


def og_html(name: str) -> str:
    return (f'<div style="width:1200px;height:630px;background:{BLACK};display:flex;align-items:center;justify-content:center;gap:56px">'
            f'{svg(100, mark("large", WHITE), 300)}'
            f'<div style="display:flex;flex-direction:column;gap:26px">{wordmark_html(name, 124, WHITE)}'
            f'<div dir="rtl" style="font:700 30px Plex, sans-serif;color:#A9AEBF;max-width:640px;line-height:1.5">{TAGLINE}</div></div></div>')


def lockup_html(name: str, dark: bool) -> str:
    bg, ink = (BLACK, WHITE) if dark else (WHITE, BLACK)
    return (f'<div style="width:1200px;height:400px;background:{bg};display:flex;align-items:center;justify-content:center;gap:40px">'
            f'{svg(100, mark("large", ink), 220)}{wordmark_html(name, 120, ink)}</div>')


def rasters(name: str) -> list[tuple[Path, int, int, str, bool]]:
    """(path, width, height, html, transparent)."""
    out = []
    adaptive_box = "0 0 108 108"
    for d, k in DENSITIES.items():
        px = round(108 * k)
        out.append((RES / f"mipmap-{d}" / "ic_launcher_foreground.png", px, px,
                    svg(108, placed("large", WHITE, FG_SCALE, view=108), px, box=adaptive_box), True))
        out.append((RES / f"mipmap-{d}" / "ic_launcher_monochrome.png", px, px,
                    svg(108, placed("large", WHITE, FG_SCALE, view=108, flat=True), px, box=adaptive_box), True))
        px = round(48 * k)
        out.append((RES / f"mipmap-{d}" / "ic_launcher.png", px, px, svg(100, tile("large", 0.7, "inset"), px), True))
        out.append((RES / f"mipmap-{d}" / "ic_launcher_round.png", px, px, svg(100, tile("large", 0.64, "circle"), px), True))
    out += [
        (RES / "drawable-nodpi" / "splash.png", 576, 576, svg(100, mark("large", WHITE), 576), True),
        (ICONS / "icon-192.png", 192, 192, svg(100, tile("large", 0.74), 192), True),
        (ICONS / "icon-512.png", 512, 512, svg(100, tile("large", 0.74), 512), True),
        (ICONS / "icon-maskable-512.png", 512, 512, svg(100, tile("large", 0.68, "full"), 512), False),
        (ICONS / "apple-touch-icon.png", 180, 180, svg(100, tile("large", 0.74, "full"), 180), False),
        (ICONS / "badge-96.png", 96, 96, svg(100, placed("small", WHITE, 0.92, flat=True), 96), True),
        (ICONS / "og-image.png", 1200, 630, og_html(name), False),
        (EXPORT / "telegram-bot-512.png", 512, 512, svg(100, tile("large", 0.7, "full"), 512), False),
        (EXPORT / "lockup-dark.png", 1200, 400, lockup_html(name, True), False),
        (EXPORT / "lockup-light.png", 1200, 400, lockup_html(name, False), False),
    ]
    return out


def favicon_frames() -> list[tuple[int, str]]:
    """favicon.ico: the small version at 16 and 32 px, the large one at 48."""
    return [(px, svg(100, tile("small" if px <= 32 else "large", 0.8 if px <= 32 else 0.74), px)) for px in (16, 32, 48)]


def chromium():
    from playwright.sync_api import sync_playwright

    path = os.environ.get("PW_CHROMIUM", "/opt/pw-browsers/chromium-1194/chrome-linux/chrome")
    pw = sync_playwright().start()
    return pw, pw.chromium.launch(**({"executable_path": path} if Path(path).exists() else {}))


def render_all(name: str) -> None:
    from PIL import Image

    pw, browser = chromium()
    try:
        page = browser.new_page(device_scale_factor=1)
        head = f"<style>{_font_face()} html,body {{ margin:0; background:transparent; }} svg {{ display:block; }}</style>"

        def shot(w: int, h: int, html: str, transparent: bool):
            page.set_viewport_size({"width": w, "height": h})
            page.set_content(f"<!doctype html><html><head><meta charset='utf-8'>{head}</head><body>{html}</body></html>")
            page.evaluate("document.fonts.ready")
            png = page.screenshot(omit_background=transparent, clip={"x": 0, "y": 0, "width": w, "height": h})
            return Image.open(io.BytesIO(png)).convert("RGBA" if transparent else "RGB")

        for path, w, h, html, transparent in rasters(name):
            path.parent.mkdir(parents=True, exist_ok=True)
            shot(w, h, html, transparent).save(path, optimize=True)
            print("  ", path.relative_to(ROOT), f"{w}×{h}")
        frames = [shot(px, px, html, True) for px, html in favicon_frames()]
    finally:
        browser.close()
        pw.stop()
    frames[-1].save(ICONS / "favicon.ico", format="ICO", sizes=[(16, 16), (32, 32), (48, 48)], append_images=frames[:-1])
    print("  ", (ICONS / "favicon.ico").relative_to(ROOT), "16/32/48")
    masks_preview()


# ------------------------------------------------------------------ Android masks (also used by the tests)

def mask(shape: str, px: int):
    """A launcher mask over the visible 72-unit centre, `px` wide."""
    from PIL import Image, ImageDraw

    m = Image.new("L", (px, px), 0)
    d = ImageDraw.Draw(m)
    if shape == "circle":
        d.ellipse((0, 0, px - 1, px - 1), fill=255)
    elif shape == "rounded":
        d.rounded_rectangle((0, 0, px - 1, px - 1), radius=round(px * 0.22), fill=255)
    elif shape == "squircle":  # |x|^4 + |y|^4 ≤ 1
        r = px / 2
        pts = []
        for i in range(720):
            t = 2 * math.pi * i / 720
            c, s = math.cos(t), math.sin(t)
            pts.append((r + r * (abs(c) ** 0.5) * (1 if c >= 0 else -1), r + r * (abs(s) ** 0.5) * (1 if s >= 0 else -1)))
        d.polygon(pts, fill=255)
    elif shape == "teardrop":  # three round corners, the bottom-right one small
        d.rounded_rectangle((0, 0, px - 1, px - 1), radius=px // 2, fill=255)
        d.rounded_rectangle((px // 2, px // 2, px - 1, px - 1), radius=round(px * 0.1), fill=255)
    return m


MASK_SHAPES = ("circle", "squircle", "rounded", "teardrop")


def masks_preview() -> None:
    from PIL import Image, ImageDraw

    fg = Image.open(RES / "mipmap-xxxhdpi" / "ic_launcher_foreground.png").convert("RGBA")  # 432 = 108 units
    mono = Image.open(RES / "mipmap-xxxhdpi" / "ic_launcher_monochrome.png").convert("RGBA")
    vis = (72, 72, 360, 360)  # the 72-unit centre the launcher shows
    tiles = []
    for layer, bg in ((fg, BLACK), (mono, "#DCE3F2")):
        for shape in MASK_SHAPES:
            base = Image.new("RGBA", (288, 288), bg)
            art = layer.crop(vis)
            if layer is mono:  # themed: the system tints the monochrome layer
                tint = Image.new("RGBA", art.size, "#1F2F4F")
                tint.putalpha(art.getchannel("A"))
                art = tint
            base.alpha_composite(art)
            out = Image.new("RGBA", (288, 288), (0, 0, 0, 0))
            out.paste(base, (0, 0), mask(shape, 288))
            tiles.append(out)
    sheet = Image.new("RGBA", (4 * 300 + 12, 2 * 300 + 12), "#2B2F3A")
    for i, t in enumerate(tiles):
        sheet.alpha_composite(t, (12 + (i % 4) * 300, 12 + (i // 4) * 300))
    d = ImageDraw.Draw(sheet)
    for i in range(4):  # the guaranteed 66-unit circle, for reference
        x0, y0 = 12 + i * 300 + 144 - 132, 12 + 144 - 132
        d.ellipse((x0, y0, x0 + 264, y0 + 264), outline=(229, 35, 45, 140))
    EXPORT.mkdir(parents=True, exist_ok=True)
    sheet.convert("RGB").save(EXPORT / "masks-preview.png", optimize=True)
    print("  ", (EXPORT / "masks-preview.png").relative_to(ROOT))


# ------------------------------------------------------------------ main

def check() -> list[str]:
    stale = [str(p.relative_to(ROOT)) for p, text in text_outputs().items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    stale += [str(p.relative_to(ROOT)) + " (missing)" for p, *_ in rasters(APP_NAME) if not p.exists()]
    stale += [str(p.relative_to(ROOT)) + " (missing)" for p in (ICONS / "favicon.ico", EXPORT / "masks-preview.png") if not p.exists()]
    return stale


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="compare the text outputs with the masters (no browser)")
    ap.add_argument("--name", default=APP_NAME, help="the name drawn in og-image and the lockups")
    args = ap.parse_args(argv)
    if args.check:
        stale = check()
        for s in stale:
            print("stale:", s)
        print("brand assets up to date" if not stale else f"{len(stale)} stale: run brand/build.py")
        return 1 if stale else 0
    for path, text in text_outputs().items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print("  ", path.relative_to(ROOT))
    render_all(args.name)
    return 0


if __name__ == "__main__":
    sys.exit(main())
