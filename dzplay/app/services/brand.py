"""V6 phase 8: the app's name (APP_NAME) for code that has no settings object at hand; phase 11c: the logo and the
name with its red dot in server-rendered pages.

During a request, the settings bound by api.deps.current_user (media_items.bind_request) are used; elsewhere the
default. Prefer settings.APP_NAME wherever settings are available. The logo's files are generated by brand/build.py
(brand/BRAND.md)."""

from __future__ import annotations

import html
import re
from functools import lru_cache
from pathlib import Path

from app.config import Settings

ICONS = Path(__file__).resolve().parents[2] / "static" / "icons"
RED = "#E5232D"  # the logo's dot (brand/BRAND.md)

# the icons in every page's <head>: favicon (ICO for old browsers, SVG), the home-screen icon on iPhone
HEAD_ICONS = ('<link rel="icon" href="/icons/favicon.ico" sizes="16x16 32x32 48x48">\n'
              '  <link rel="icon" href="/icons/icon.svg" type="image/svg+xml">\n'
              '  <link rel="apple-touch-icon" href="/icons/apple-touch-icon.png">')


def app_name() -> str:
    from app.services.media_items import _settings

    s = _settings()
    return s.APP_NAME if s is not None else Settings.model_fields["APP_NAME"].default


def team_name(lang: str | None = None) -> str:
    from app.i18n import tr

    return tr("فريق {app}", lang, app=app_name())


def official_name(lang: str | None = None) -> str:
    from app.i18n import tr

    return tr("{app} الرسمي", lang, app=app_name())


def wordmark_html(name: str) -> str:
    """The name for HTML with the logo's red dot (DALTA.BIT → DALTA●BIT); without a dot in the name, the dot follows
    it. Style: .wordmark__dot (app.css / download.css)."""
    first, dot, rest = name.partition(".")
    return f'{html.escape(first)}<span class="wordmark__dot"></span>{html.escape(rest) if dot else ""}'


@lru_cache(maxsize=4)
def logo_svg(size: int = 96, cls: str = "logo-mark logo-mark--pulse") -> str:
    """The large logo inline, for HTML shown before (or without) JavaScript: plain shapes and the dot's gradients,
    no script and no style attribute (the CSP allows it). The candles take the text colour."""
    text = re.sub(r"<!--.*?-->\s*", "", (ICONS / "logo-large.svg").read_text(encoding="utf-8"), flags=re.S)
    tag = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100" width="{size}" height="{size}" '
           f'class="{cls}" aria-hidden="true" focusable="false">')
    return re.sub(r"<svg[^>]*>", tag, text, count=1).strip()


OG_LOCALES = {"ar": "ar_AR", "fr": "fr_FR", "en": "en_GB"}


def og_tags(settings: Settings, base: str, title: str, description: str, lang: str = "ar") -> str:
    """Link previews (Telegram, WhatsApp, X…): the og-image made by brand/build.py, at an absolute URL."""
    e = html.escape
    image = f"{base.rstrip('/')}/icons/og-image.png"
    return "\n  ".join((
        '<meta property="og:type" content="website">',
        f'<meta property="og:site_name" content="{e(settings.APP_NAME)}">',
        f'<meta property="og:title" content="{e(title)}">',
        f'<meta property="og:description" content="{e(description)}">',
        f'<meta property="og:image" content="{e(image)}">',
        '<meta property="og:image:width" content="1200">',
        '<meta property="og:image:height" content="630">',
        f'<meta property="og:locale" content="{OG_LOCALES.get(lang, "ar_AR")}">',
        '<meta name="twitter:card" content="summary_large_image">',
        f'<meta name="twitter:image" content="{e(image)}">',
    ))


def email_name_html(name: str) -> str:
    """The name at the top of an email: text (an image may be blocked), its dot in the logo's red — a coloured «.»
    that every mail client shows."""
    first, dot, rest = name.partition(".")
    if not dot:
        return html.escape(name)
    return f'{html.escape(first)}<span style="color:{RED}">.</span>{html.escape(rest)}'
